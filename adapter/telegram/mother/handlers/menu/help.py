from aiogram.types import Message
from aiogram.filters import StateFilter
from aiogram import F

from . import router



@router.message(StateFilter(None),F.text == "🆘 راهنما")
async def handler_help(message:Message):
    await message.answer("""
قبل از ساخت ربات بهتر است با روند صحیح ساخت ربات آشنا شوید.
به همین منظور این آموزش را برای شما آماده کرده‌ایم.


مرحله اول : ساخت ربات 1️⃣


• وارد ربات @BotFather شوید.

• روی دکمه Start کلیک کنید.

• از بین دستورات، گزینه ساخت ربات جدید ( معمولاً newbot ) را انتخاب کنید.

• در مرحله اول، BotFather از شما نام نمایشی ربات را درخواست می‌کند. این نام در بالای صفحه ربات، کنار تصویر پروفایل نمایش داده می‌شود و می‌تواند فارسی یا انگلیسی باشد.

• در مرحله بعد باید یک شناسه ( Username ) برای ربات انتخاب کنید.


قوانین ساخت شناسه :


• فقط از حروف انگلیسی استفاده کنید.

• حروف بزرگ و کوچک با یکدیگر تفاوت دارند.

• انتهای شناسه حتماً باید Bot یا bot_ باشد.


پس از ساخت ربات، BotFather یک Token در اختیار شما قرار می‌دهد.

معمولاً این Token زیر جمله :

Use this token to access the HTTP API

قرار دارد.

با لمس Token، می‌توانید آن را کپی کنید.

برای ساخت و فعال‌سازی ربات کافی است Token را داخل ربات مادر وارد کنید.
از منوی اصلی روی گزینه «ساخت ربات» کلیک کرده و مراحل را به ترتیب انجام دهید.


مرحله دوم : تنظیمات ربات 2️⃣


در این مرحله تنظیمات اولیه ربات مانند تصویر پروفایل، توضیحات و بنر را انجام می‌دهیم.

تمام این تنظیمات داخل ربات @BotFather انجام می‌شود و ارتباطی با ربات مادر ندارد.


• وارد BotFather شوید.

• روی Start کلیک کنید.

• گزینه mybots را انتخاب کنید.

• ربات مورد نظر خود را انتخاب کنید.

• وارد بخش Edit Bot شوید.


در این قسمت گزینه‌های زیر را مشاهده می‌کنید:


• Edit Name :

تغییر نام نمایشی ربات


• Edit About :

نوشتن توضیح کوتاه ربات که در پروفایل نمایش داده می‌شود


• Edit Description :

نوشتن توضیحات صفحه شروع ربات که قبل از استارت به کاربران نمایش داده می‌شود


• Edit Description Picture :

قرار دادن بنر یا تصویر بالای توضیحات صفحه شروع ربات. توجه کنید اندازه تصویر باید مطابق استاندارد تعیین شده توسط BotFather باشد


• Edit Botpic :

تغییر تصویر پروفایل ربات. اندازه تصویر باید مطابق استاندارد BotFather باشد


هشدار ⚠️


از تغییر سایر تنظیمات ربات خودداری کنید.

در صورت نیاز به تنظیم اضافی، آموزش در ربات مادر موجود است
""")
